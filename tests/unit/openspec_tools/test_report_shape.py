"""Unit tests for the threat-model report shape check (openspec/tools/report_shape.py).

The check is a leak guard: a committed report may hold only counts, the gate
result and the model hash. It must work without access to the private model.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

_REPO = Path(__file__).resolve().parents[3]
_PATH = _REPO / "openspec" / "tools" / "report_shape.py"
_spec = importlib.util.spec_from_file_location("openspec_tools_report_shape", _PATH)
assert _spec and _spec.loader
shape = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(shape)

_SHA = "0" * 64


def _report(
    model: str = "my-change.tc.json", sha: str = _SHA, gate: str = "PASSED", count: int = 3
) -> str:
    return (
        "# Threat model report\n\n"
        "<!-- Generated by `python3 openspec/tools/tc.py report`. Do not edit. -->\n\n"
        "| Field | Value |\n|---|---|\n"
        f"| Model | `{model}` |\n| Model SHA-256 | `{sha}` |\n| Gate | {gate} |\n"
        f"| Threats | {count} |\n| Mitigations | {count} |\n| Assumptions | {count} |\n"
    )


def test_accepts_a_sanitized_report():
    assert shape.check_report_shape(_report()) == []
    assert shape.check_report_shape(_report(gate="FAILED (propose)")) == []


def test_accepts_a_skipped_report_and_detects_it():
    skipped = _report(model="none", sha="none", gate="SKIPPED", count=0)
    assert shape.check_report_shape(skipped) == []
    assert shape.is_skipped(skipped)
    assert not shape.is_skipped(_report())


def test_rejects_an_added_line():
    assert shape.check_report_shape(_report() + "| Threat | SECRET |\n")


def test_rejects_an_edited_value():
    tampered = _report().replace("| Gate | PASSED |", "| Gate | PASSED, see T3 |")
    assert shape.check_report_shape(tampered) == ["line 9: unexpected content"]


def test_template_has_the_same_line_count_as_the_shape():
    template = (_REPO / "openspec/schemas/cairn/templates/threat-model-report.md").read_text(
        encoding="utf-8"
    )
    assert template.splitlines()[0] == _report().splitlines()[0]
    assert len(template.splitlines()) == len(_report().splitlines())


def test_committed_reports_contain_only_sanitized_fields():
    reports = sorted((_REPO / "openspec" / "changes").glob("**/threat-model-report.md"))
    problems = {
        str(p.relative_to(_REPO)): shape.check_report_shape(p.read_text(encoding="utf-8"))
        for p in reports
    }
    assert {k: v for k, v in problems.items() if v} == {}


def test_no_archived_report_is_skipped():
    archived = sorted(
        (_REPO / "openspec" / "changes" / "archive").glob("**/threat-model-report.md")
    )
    skipped = [
        str(p.relative_to(_REPO))
        for p in archived
        if shape.is_skipped(p.read_text(encoding="utf-8"))
    ]
    assert skipped == [], "a maintainer must run the threat-model step before archiving"
