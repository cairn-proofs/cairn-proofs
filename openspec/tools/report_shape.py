"""Shape check for the committed threat-model report.

The threat model is private; `openspec/changes/**/threat-model-report.md` is the
one public trace of it. It may hold only counts, the gate result and the model
hash. This module checks that no other text, such as hand-added threat detail,
is in a report. It needs no access to the private repository, so it runs in
public CI.

The report is generated by `tools/tc.py` in the private threat-model repo (see
`openspec/schemas/cairn/schema.yaml`). A contributor with no access to that repo
writes a SKIPPED report instead, with `none` for the model and its hash. A
maintainer replaces it before merge, so a SKIPPED report must never be archived.

Stdlib-only.
"""

from __future__ import annotations

import re

# Every line a report may contain; `{...}` marks where a value goes.
_TEMPLATE_LINES = [
    "# Threat model report",
    "",
    "<!-- Generated by `python3 openspec/tools/tc.py report`. Do not edit. -->",
    "",
    "| Field | Value |",
    "|---|---|",
    "| Model | `{model}` |",
    "| Model SHA-256 | `{sha256}` |",
    "| Gate | {gate} |",
    "| Threats | {count} |",
    "| Mitigations | {count} |",
    "| Assumptions | {count} |",
]

_VALUE_PATTERNS = {
    "model": r"(?:[a-z0-9][a-z0-9-]*\.tc\.json|none)",
    "sha256": r"(?:[0-9a-f]{64}|none)",
    "gate": r"(?:(?:PASSED|FAILED)(?: \(propose\))?|SKIPPED)",
    "count": r"\d+",
}


def _pattern(line: str) -> str:
    pattern = re.escape(line)
    for name, value in _VALUE_PATTERNS.items():
        pattern = pattern.replace(re.escape("{" + name + "}"), value)
    return pattern


_LINE_PATTERNS = [_pattern(line) for line in _TEMPLATE_LINES]


def check_report_shape(text: str) -> list[str]:
    """Return the problems that keep `text` from being exactly a sanitized report."""
    lines = text.splitlines()
    if len(lines) != len(_LINE_PATTERNS):
        return [f"expected {len(_LINE_PATTERNS)} lines, found {len(lines)}"]
    return [
        f"line {n}: unexpected content"
        for n, (line, pattern) in enumerate(zip(lines, _LINE_PATTERNS, strict=True), start=1)
        if not re.fullmatch(pattern, line)
    ]


def is_skipped(text: str) -> bool:
    """True for a report written because the contributor had no access to the model."""
    return "| Gate | SKIPPED |" in text.splitlines()
